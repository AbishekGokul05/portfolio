const fs = require('node:fs/promises');
const path = require('node:path');
const sharp = require('sharp');

(async () => {
  const manifest = {};
  let originalBytes = 0;
  let optimizedBytes = 0;
  for (const folder of ['profile', 'projects']) {
    const directory = path.join('assets', 'images', folder);
    for (const name of (await fs.readdir(directory)).filter(name => name.endsWith('.png'))) {
      const source = path.join(directory, name);
      const { width, height } = await sharp(source).metadata();
      const sizes = [...new Set([480, 800, 1200].map(size => Math.min(size, width)))];
      const variants = [];
      for (const size of sizes) {
        const output = source.replace('.png', `-${size}.webp`);
        await sharp(source).resize({ width: size, withoutEnlargement: true }).webp({ quality: 84, effort: 6 }).toFile(output);
        variants.push({ src: output.replaceAll('\\', '/'), width: size });
      }
      originalBytes += (await fs.stat(source)).size;
      optimizedBytes += (await fs.stat(variants.at(-1).src)).size;
      manifest[source.replaceAll('\\', '/')] = { width, height, variants };
    }
  }
  await fs.writeFile('js/image-manifest.js', `/* Generated by npm run images. Original assets are retained. */\nwindow.portfolioImages = ${JSON.stringify(manifest, null, 2)};\n`);
  console.log(`Largest image variants: ${(optimizedBytes / 1024 / 1024).toFixed(2)} MB; original PNGs: ${(originalBytes / 1024 / 1024).toFixed(2)} MB.`);
})();
